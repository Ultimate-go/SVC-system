/**
 * SM4 分组密码 + CTR 模式 —— 国标 GB/T 32907-2016。
 *
 * 用途：解开**块密钥**（`keywrap.js`）与**块内容**（本文件）。
 * 与 Python 侧 `core.crypto.encrypt_segment/decrypt_segment`
 * （`cryptography` 的 `algorithms.SM4` + `modes.CTR`）必须逐字节相同。
 *
 * CTR 的计数器约定（这一条错了就全错）
 * ------------------------------------
 * `cryptography` 的 `modes.CTR(iv)` 把**整个 16 字节 IV 当作大端计数器**，
 * 每生成一个密钥流分组就 +1（128 位大端递增，进位跨字节）。
 * 所以这里是 `ctr = iv`，每块 `incrCtr()`，不是"只用低 32 位"也不是小端。
 *
 * CTR 是对合运算（加解密同一条路径），所以本模块只导出 `sm4Ctr`。
 */

