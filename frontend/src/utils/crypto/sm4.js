/** 系统参数 FK。 */
const FK = [0xa3b1bac6, 0x56aa3350, 0x677d9197, 0xb27022dc]

/** 固定参数 CK —— `CK[i]` 的四个字节是 `(4i+j)·7 mod 256`。 */
const CK = new Uint32Array(32)
for (let i = 0; i < 32; i++) {
  let w = 0
  for (let j = 0; j < 4; j++) w = (w << 8) | (((4 * i + j) * 7) & 0xff)
  CK[i] = w >>> 0
}

const rotl = (x, n) => ((x << n) | (x >>> (32 - n))) >>> 0

/** τ：逐字节过 S 盒。 */
const tau = (x) =>
  (((SBOX[(x >>> 24) & 0xff] << 24) |
    (SBOX[(x >>> 16) & 0xff] << 16) |
    (SBOX[(x >>> 8) & 0xff] << 8) |
    SBOX[x & 0xff]) >>>
    0)

/** 轮函数合成 T = L(τ(x))。 */
const T = (x) => {
  const b = tau(x)
  return (b ^ rotl(b, 2) ^ rotl(b, 10) ^ rotl(b, 18) ^ rotl(b, 24)) >>> 0
}

/** 密钥扩展里的 T' = L'(τ(x))。 */
const Tp = (x) => {
  const b = tau(x)
  return (b ^ rotl(b, 13) ^ rotl(b, 23)) >>> 0
}

/** 由 16 字节密钥算出 32 个轮密钥。 */
function keySchedule(key) {
  const dv = new DataView(key.buffer, key.byteOffset, key.byteLength)
  const K = new Uint32Array(36)
  K[0] = (dv.getUint32(0) ^ FK[0]) >>> 0
  K[1] = (dv.getUint32(4) ^ FK[1]) >>> 0
  K[2] = (dv.getUint32(8) ^ FK[2]) >>> 0
  K[3] = (dv.getUint32(12) ^ FK[3]) >>> 0
  const rk = new Uint32Array(32)
  for (let i = 0; i < 32; i++) {
    K[i + 4] = (K[i] ^ Tp((K[i + 1] ^ K[i + 2] ^ K[i + 3] ^ CK[i]) >>> 0)) >>> 0
    rk[i] = K[i + 4]
  }
  return rk
}

/**
 * 用轮密钥处理一个 16 字节分组。CTR 只需要加密方向。
 *
 * @param {Uint8Array} block 16 字节输入
 * @param {Uint32Array} rk 32 个轮密钥
 */
function encryptBlockWithRk(block, rk) {
  const dv = new DataView(block.buffer, block.byteOffset, block.byteLength)
  const X = new Uint32Array(36)
  X[0] = dv.getUint32(0)
  X[1] = dv.getUint32(4)
  X[2] = dv.getUint32(8)
  X[3] = dv.getUint32(12)
  for (let i = 0; i < 32; i++) {
    X[i + 4] = (X[i] ^ T((X[i + 1] ^ X[i + 2] ^ X[i + 3] ^ rk[i]) >>> 0)) >>> 0
  }
  const out = new Uint8Array(16)
  const odv = new DataView(out.buffer)
  // 反序输出（X35, X34, X33, X32）
  odv.setUint32(0, X[35])
  odv.setUint32(4, X[34])
  odv.setUint32(8, X[33])
  odv.setUint32(12, X[32])
  return out
}

/** 计数器自增（128 位大端，进位跨字节）。 */
function incrCtr(ctr) {
  for (let i = 15; i >= 0; i--) {
    ctr[i] = (ctr[i] + 1) & 0xff
    if (ctr[i] !== 0) break
  }
}

/**
 * SM4-CTR（加解密同一条路径）。
 *
 * @param {Uint8Array} data 输入字节
 * @param {Uint8Array} key 16 字节密钥
 * @param {Uint8Array} iv 16 字节初始计数器
 * @returns {Uint8Array} 与输入等长的输出
 */
export function sm4Ctr(data, key, iv) {
  if (key.length !== 16) throw new Error(`SM4 密钥必须是 16 字节，收到 ${key.length}`)
  if (iv.length !== 16) throw new Error(`IV 必须是 16 字节，收到 ${iv.length}`)
  const rk = keySchedule(key)
  const ctr = Uint8Array.from(iv)
  const out = new Uint8Array(data.length)
  for (let off = 0; off < data.length; off += 16) {
    const ks = encryptBlockWithRk(ctr, rk)
    const n = Math.min(16, data.length - off)
    for (let i = 0; i < n; i++) out[off + i] = data[off + i] ^ ks[i]
    incrCtr(ctr)
  }
  return out
}
